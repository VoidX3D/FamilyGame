/* Builds the icon set.
 *
 * The icons are Lucide's, which are real, licensed SVG files rather than
 * paths typed into a JavaScript file by hand. The .svg files are copied
 * into web/assets/icons, and web/icons.js is generated from them, so the
 * icons can be replaced, corrected or added to without touching the
 * markup.
 *
 *   npm run icons            build
 *   npm run icons -- --check fail if web/icons.js is out of date
 *
 * The source is the lucide-static package, which is a dev dependency, so
 * nothing is added to what the browser downloads.
 */

