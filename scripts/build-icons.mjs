/* The shape of web/icons.js. The paths are filled in from the .svg files. */
function template(paths) {
  return `/* Made by VoidX3D (Sincere Bhattarai) - Family Game Hub */
/* The icon set.
 *
 * Generated by scripts/build-icons.mjs from the Lucide SVG files in
 * web/assets/icons. Do not edit this file by hand: run "npm run icons"
 * instead. The icons themselves are Lucide's, under the ISC licence.
 */
const SVG_NS = "http://www.w3.org/2000/svg";

const PATHS = {
${paths}
};

/* The icon each game is shown with in the catalogue. */
const GAME_ICONS = ${JSON.stringify(GAME_ICONS, null, 2).replace(/\n/g, "\n")};

export function icon(name, { className = "", size = 20 } = {}) {
  const svg = document.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.8");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.setAttribute("class", \`icon \${className}\`.trim());
  svg.dataset.iconName = name;
  svg.innerHTML = PATHS[name] ?? PATHS.sparkles;
  return svg;
}

/* The icon for a game, from the game id. */
export function gameIcon(gameId) {
  return GAME_ICONS[gameId] ?? "dice";
}

/* Replaces every [data-icon] placeholder with the real icon. */
export function hydrateIcons(root = document) {
  for (const host of root.querySelectorAll("[data-icon]")) {
    if (host.dataset.iconReady === "true") continue;
    host.replaceChildren(icon(host.dataset.icon));
    host.dataset.iconReady = "true";
  }
}

export const ICON_NAMES = Object.keys(PATHS);
`;
}

/* Pulls the markup out of an SVG file: everything inside the <svg> tag. */
function bodyOf(svg) {
  const match = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/i);
  return (match?.[1] ?? "").trim();
}

async function main() {
  const check = process.argv.includes("--check");

  const available = new Set(
    (await readdir(source)).filter((name) => name.endsWith(".svg")),
  );

  const missing = Object.values(ICONS).filter((name) => !available.has(`${name}.svg`));
  if (missing.length > 0) {
    console.error(`These Lucide icons do not exist: ${missing.join(", ")}`);
    process.exit(1);
  }

  await mkdir(target, { recursive: true });

  const entries = [];
  for (const [name, lucide] of Object.entries(ICONS)) {
    const file = path.join(source, `${lucide}.svg`);
    await copyFile(file, path.join(target, `${name}.svg`));
    const markup = bodyOf(await readFile(file, "utf8"));
    entries.push(
      `  ${JSON.stringify(name)}:\n    ${JSON.stringify(markup)},`,
    );
  }

  const generated = template(entries.join("\n"));

  if (check) {
    const current = await readFile(output, "utf8").catch(() => "");
    if (current !== generated) {
      console.error(
        "web/icons.js is out of date. Run: npm run icons",
      );
      process.exit(1);
    }
    console.log(`icons are up to date (${entries.length})`);
    return;
  }

  await writeFile(output, generated, "utf8");
  console.log(
    `Wrote ${entries.length} icons to web/icons.js and web/assets/icons.`,
  );
}

await main();
