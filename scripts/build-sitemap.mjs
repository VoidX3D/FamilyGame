/* Builds the sitemap and the robots file.
 *
 * Both come from web/manus-routes.json, which is the list of the pages
 * the site has. One list, so the sitemap and the robots rules cannot
 * drift apart from the pages that actually exist.
 *
 *   npm run sitemap          build
 *   npm run sitemap -- --check   fail if either file is out of date
 *
 * The script also checks that every route in the list has a page behind
 * it, so a route that is renamed without being updated here is caught
 * rather than quietly left in the sitemap.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DEPLOYED_WEB } from "../web/endpoints.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const web = path.join(root, "web");

const MANIFEST = path.join(web, "manus-routes.json");
const SITEMAP = path.join(web, "sitemap.xml");
const ROBOTS = path.join(web, "robots.txt");

const SITE = DEPLOYED_WEB;

/* The pages that are not for the public. They are kept out of the
 * sitemap and pushed away in the robots file. */
const PRIVATE_PREFIXES = ["/admin", "/g/", "/game", "/api"];

function isPrivate(routePath) {
  return PRIVATE_PREFIXES.some((prefix) => routePath.startsWith(prefix));
}

/* The page a route ends up on. The rewrites in vercel.json point the
 * clean paths at these files. A route with a parameter opens the player
 * shell, because that is where the invite link lands. */
function pageFor(routePath) {
  if (routePath === "/") return "index.html";
  const parts = routePath.split("/").filter(Boolean);
  if (parts.some((part) => part.startsWith(":"))) return "index.html";
  return `${parts[0] ?? ""}.html`;
}

function sitemapFor(routes) {
  const entries = routes
    .filter((route) => !isPrivate(route.path))
    .map(
      (route) => `  <url>
    <loc>${SITE}${route.path === "/" ? "/" : route.path}</loc>
    <changefreq>${route.path === "/" ? "weekly" : "monthly"}</changefreq>
    <priority>${route.path === "/" ? "0.8" : "0.4"}</priority>
  </url>`,
    )
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Made by VoidX3D (Sincere Bhattarai) - Family Game Hub -->
<!-- Generated by scripts/build-sitemap.mjs from web/manus-routes.json. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</urlset>
`;
}

function robotsFor(routes) {
  /* The fixed list, plus anything private in the manifest that is not
   * already covered by it. */
  const fixed = PRIVATE_PREFIXES.map((prefix) => `Disallow: ${prefix}`);
  const covered = new Set(
    PRIVATE_PREFIXES.map((prefix) => prefix.replace(/\/+$/, "")),
  );

  const fromManifest = routes
    .filter((route) => isPrivate(route.path))
    .map((route) => `/${route.path.split("/")[1]}`)
    .filter((name) => name && name !== "/")
    .filter((name) => !covered.has(name.replace(/\/+$/, "")))
    .map((name) => `Disallow: ${name}`);

  const unique = [...new Set([...fixed, ...fromManifest])].sort();

  return `# Family Game Hub - a private party game for the family.
#
# The game itself is meant to be found through the invite link that the
# host shares, so the public pages are only the ones a person might land
# on from a search.
#
# Generated by scripts/build-sitemap.mjs from web/manus-routes.json.

User-agent: *
Allow: /$
Allow: /about
Allow: /privacy
Allow: /terms
${unique.join("\n")}

Sitemap: ${SITE}/sitemap.xml
`;
}

async function main() {
  const check = process.argv.includes("--check");

  const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
  const routes = Array.isArray(manifest.routes) ? manifest.routes : [];
  if (routes.length === 0) {
    console.error("The route manifest has no routes.");
    process.exit(1);
  }

  /* Every route has to have a page behind it. */
  const missing = [];
  for (const route of routes) {
    const page = pageFor(route.path);
    try {
      await readFile(path.join(web, page));
    } catch {
      missing.push(`${route.path} (${page})`);
    }
  }
  if (missing.length > 0) {
    console.error(`These routes have no page: ${missing.join(", ")}`);
    process.exit(1);
  }

  const sitemap = sitemapFor(routes);
  const robots = robotsFor(routes);

  if (check) {
    const currentSitemap = await readFile(SITEMAP, "utf8").catch(() => "");
    const currentRobots = await readFile(ROBOTS, "utf8").catch(() => "");
    if (currentSitemap !== sitemap || currentRobots !== robots) {
      console.error(
        "web/sitemap.xml or web/robots.txt is out of date. Run: npm run sitemap",
      );
      process.exit(1);
    }
    console.log(`the sitemap and the robots file are up to date (${routes.length} routes)`);
    return;
  }

  await writeFile(SITEMAP, sitemap, "utf8");
  await writeFile(ROBOTS, robots, "utf8");
  console.log(
    `Wrote web/sitemap.xml and web/robots.txt from ${routes.length} routes.`,
  );
}

await main();
